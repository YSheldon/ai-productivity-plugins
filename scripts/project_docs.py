"""Generate the public plugin catalog and check scoped showcase documentation."""
from __future__ import annotations

import argparse
import ipaddress
import json
import re
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
DOCUMENTS = [Path(name) for name in (
    "README.md", "CHANGELOG.md", "docs/plugin-catalog.md", "docs/installation.md",
    "docs/remotex-showcase.md", "docs/maintaining-project-docs.md", "plugins/remotex/README.md",
)]
GROUPS = {
    "Remote Operations": {"remotex"},
    "GitLab and CI": {"gitlab"},
    "Release and Approval": {"product-release-gate", "test-submission", "submission-gate",
        "pre-release", "release-gate", "release-approval", "release-approval-verifier"},
    "Collaboration and Reporting": {"imap-smtp-mail", "lark-cli", "wecom-codex-usage", "daily-vuln-bulletin-email"},
    "Engineering Utilities": {"rd-flywheel", "world-time-reminder"},
}


def read_json(path: Path) -> dict:
    return json.loads(path.read_text(encoding="utf-8"))


def cell(value: str) -> str:
    return " ".join(value.split()).replace("|", "&#124;")


def render_catalog(root: Path) -> str:
    codex = read_json(root / ".agents/plugins/marketplace.json")["plugins"]
    cursor = {p["name"] for p in read_json(root / ".cursor-plugin/marketplace.json")["plugins"]}
    grok = {p["name"] for p in read_json(root / ".grok-plugin/marketplace.json")["plugins"]}
    available = [p for p in codex if p.get("policy", {}).get("installation") == "AVAILABLE"]
    legacy = [p for p in codex if p not in available]
    lines = ["# Plugin Catalog", "", "[Home](../README.md) | [Install](installation.md) | [What's new](../CHANGELOG.md)", "",
        "<!-- Generated by scripts/project_docs.py; do not edit version/membership tables. -->", "",
        f"{len(available)} available plugins. Versions and client-index membership are generated from repository manifests.", "",
        "**Yes means available in the Codex index, or listed in the Cursor/Grok index, not tested on every client or operating system.** No means unavailable or not listed, not a technical impossibility.", "",
        "## Compatibility and Evidence", "",
        "- Current Cursor MCP wrappers require Windows; check each plugin's guide for its actual platform prerequisites.",
        "- RemoteX web credentials require Windows, Edge, Node.js 24+, and the pinned browser runtime.",
        "- Lark requires a separately installed/authenticated CLI; release workflows require configured local adapters.",
        "- The repository Windows CI provides fixture/regression evidence, not universal production acceptance.",
        "- Installation, tool discovery, credential presence, and authenticated acceptance are separate checks.", ""]
    grouped = {group: [p for p in available if p["name"] in names] for group, names in GROUPS.items()}
    known = set().union(*GROUPS.values())
    grouped["Other Plugins"] = [p for p in available if p["name"] not in known]
    grouped["Legacy"] = legacy
    for group, entries in grouped.items():
        if not entries:
            continue
        lines += [f"## {group}", ""]
        if group == "Remote Operations":
            lines += ["Explore [web sign-in, scoped certificate trust, and per-credential reports](remotex-showcase.md).", ""]
        if group == "Legacy":
            lines += ["Unavailable for new Codex installation. Use RemoteX instead of the legacy SSH entry.", ""]
        lines += ["| Plugin / guide | Version | Codex | Cursor | Grok | Purpose |", "| --- | --- | --- | --- | --- | --- |"]
        for entry in entries:
            name = entry["name"]
            manifest = read_json(root / "plugins" / name / ".codex-plugin/plugin.json")
            if manifest["name"] != name:
                raise ValueError(f"Plugin manifest name mismatch: {name}")
            flags = ["Yes" if value else "No" for value in (entry in available, name in cursor, name in grok)]
            lines.append(f"| [{name}](../plugins/{name}/README.md) | {cell(manifest['version'])} | {' | '.join(flags)} | {cell(manifest['description'])} |")
        lines.append("")
    lines += ["## Where to Start", "",
        "Follow the [installation guide](installation.md#first-use) for first-run setup, or the",
        "[RemoteX showcase](remotex-showcase.md) for report and credential workflows.", "",
        "IMAP/SMTP Mail is adapted from [gzlicanyi's original skill](https://github.com/openclaw/skills/tree/main/skills/gzlicanyi/imap-smtp-email).",
        "See each plugin's guide and the repository [license](../LICENSE) for attribution.", ""]
    return "\n".join(lines)


def check_documents(root: Path, documents: list[Path]) -> list[str]:
    errors = []
    for relative in documents:
        file = root / relative
        if not file.is_file():
            errors.append(f"Missing document: {relative}")
            continue
        text = file.read_text(encoding="utf-8")
        if re.search(r"[\u3400-\u9fff]", text):
            errors.append(f"English-only documentation required: {relative}")
        for url in re.findall(r"https?://[^\s<>\]\)]+", text):
            try:
                address = ipaddress.ip_address(urlsplit(url).hostname or "")
            except ValueError:
                continue
            if address.is_private:
                errors.append(f"Literal private endpoint in {relative}")
        # The maintained documents use inline Markdown links without titles.
        for target in re.findall(r"!?\[[^\]\n]*\]\(([^)\n]+)\)", text):
            parsed = urlsplit(target.strip("<>"))
            if parsed.scheme or parsed.netloc:
                continue
            destination = (file.parent / unquote(parsed.path)).resolve() if parsed.path else file.resolve()
            if not destination.is_relative_to(root.resolve()) or not destination.exists():
                errors.append(f"Broken local link in {relative}: {target}")
            elif parsed.fragment and destination.suffix.lower() == ".md":
                if unquote(parsed.fragment) not in heading_ids(destination.read_text(encoding="utf-8")):
                    errors.append(f"Broken heading link in {relative}: {target}")
    return errors


def heading_ids(text: str) -> set[str]:
    result, counts = set(), {}
    fenced = False
    for line in text.splitlines():
        if line.startswith(("```", "~~~")):
            fenced = not fenced
            continue
        match = re.match(r"^#{1,6}\s+(.+?)\s*#*\s*$", line) if not fenced else None
        if not match:
            continue
        slug = re.sub(r"[^\w\s-]", "", match.group(1).lower()).replace(" ", "-")
        count = counts.get(slug, 0)
        result.add(slug if not count else f"{slug}-{count}")
        counts[slug] = count + 1
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = render_catalog(ROOT)
    target = ROOT / "docs/plugin-catalog.md"
    if args.write:
        target.write_text(expected, encoding="utf-8", newline="\n")
        print("Updated docs/plugin-catalog.md")
        return 0
    errors = check_documents(ROOT, DOCUMENTS)
    if not target.exists() or target.read_text(encoding="utf-8") != expected:
        errors.append("Plugin catalog is stale; run python scripts/project_docs.py --write")
    for error in errors:
        print(error)
    if not errors:
        print(f"Project documentation OK: catalog current, {len(DOCUMENTS)} documents checked")
    return int(bool(errors))


if __name__ == "__main__":
    raise SystemExit(main())
